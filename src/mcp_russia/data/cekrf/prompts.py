"""Промпты для анализа данных ЦИК РФ."""

from fastmcp import Context


async def analiz_kandidata(
    fio: str,
    god: int,
    ctx: Context,
) -> str:
    """Промпт для комплексного анализа кандидата.

    Генерирует последовательность шагов для получения
    полной информации о кандидате: поиск, биография,
    финансы, результаты голосования.

    Аргументы:
        fio: ФИО кандидата.
        god: Год выборов.
        ctx: Контекст MCP.

    Возвращает:
        Инструкции по анализу кандидата.
    """
    return (
        f"Проведите комплексный анализ кандидата '{fio}' "
        f"на выборах {god} года в РФ.\n\n"
        "Шаги анализа:\n"
        "1. Используйте poisk_kandidata(fio, god) для поиска кандидата\n"
        "2. Используйте kandidat_podrobno(kandidat_id, god) для получения:\n"
        "   - Биографических данных (дата/место рождения, образование)\n"
        "   - Места работы и должности\n"
        "   - Декларации о доходае и имуществе\n"
        "3. Используйте rezultaty_vyborov(god) для результатов\n"
        "4. Подготовьте отчёт:\n"
        "   - Краткая биография\n"
        "   - Финансовое положение (доход, имущество)\n"
        "   - Результаты голосования\n\n"
        "Примечание: данные ЦИК РФ могут быть неполными. "
        "Для детальной информации используйте cikrf.ru и "
        "ГАС «Выборы» (vybory.izbirkom.ru)."
    )


async def sravnenie_partiy(
    god: int,
    ctx: Context,
) -> str:
    """Промпт для сравнения результатов партий на выборах.

    Аргументы:
        god: Год выборов.
        ctx: Контекст MCP.

    Возвращает:
        Инструкции по сравнению партий.
    """
    return (
        f"Сравните результаты политических партий на выборах {god} года в РФ.\n\n"
        "Шаги анализа:\n"
        "1. Используйте partii_rf() для получения справочника партий\n"
        "2. Используйте rezultaty_vyborov(god) для получения результатов\n"
        "3. Используйте yavka_i_itogi(god) для данных о явке\n"
        "4. Подготовте сравнительный анализ:\n"
        "   - Распределение голосов по партиям\n"
        "   - Процентное соотношение\n"
        "   - Влияние явки на результаты\n"
        "   - Сравнение с предыдущими выборами (если доступно)\n\n"
        "Примечание: для исторических данных используйте "
        "архивы cikrf.ru."
    )
