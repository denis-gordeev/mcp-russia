"""Промпты модуля Официальные публикации РФ."""

from __future__ import annotations

from fastmcp import Context


async def analiz_normativnogo_akta(context: str, ctx: Context) -> str:
    """Анализ нормативного правового акта.

    Args:
        context: Контекст запроса (например, "анализ ФЗ № 44").

    Returns:
        Prompt template for legal act analysis.
    """
    return (
        f"Выполни анализ нормативного правового акта.\n\n"
        f"Контекст: {context}\n\n"
        f"Инструкция:\n"
        f"1. Определи номер и тип акта\n"
        f"2. Получи информацию об акте через info_normativnogo_akta()\n"
        f"3. Изучи изменения через izmeneniya_akta()\n"
        f"4. Определи текущий статус акта\n"
        f"5. Дай краткую характеристику акта\n\n"
        f"Важно: обращай внимание на статус (действующий/утратил силу) "
        f"и дату последних изменений."
    )


async def obzor_zakonodatelstva(ctx: Context) -> str:
    """Обзор изменений в законодательстве за период.

    Returns:
        Prompt template for legislative overview.
    """
    return (
        "Подготовь обзор изменений в законодательстве за период.\n\n"
        "Инструкция:\n"
        "1. Получи публикации за период через publikatsii_po_datam()\n"
        "2. Отметь ключевые законы и изменения\n"
        "3. Проанализируй тенденции в законодательстве\n"
        "4. Выдели наиболее значимые акты\n"
        "5. Оформи как аналитическую справку\n\n"
        "Важно: указывай источники публикаций и даты принятия актов."
    )
