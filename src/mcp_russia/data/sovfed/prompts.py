"""Промпты модуля Совета Федерации РФ."""

from __future__ import annotations

from fastmcp import Context


async def analiz_senatora(context: str, ctx: Context) -> str:
    """Анализ деятельности сенатора Совета Федерации.

    Args:
        context: Контекст запроса (например, "анализ сенатора Иванова от Москвы").

    Returns:
        Prompt template for senator analysis.
    """
    return (
        f"Выполни анализ деятельности сенатора Совета Федерации РФ.\n\n"
        f"Контекст: {context}\n\n"
        f"Инструкция:\n"
        f"1. Получи информацию о сенаторе через info_senatora()\n"
        f"2. Определи регион представления и должность\n"
        f"3. Изучи членство в комитете/комиссии\n"
        f"4. Проанализируй законотворческую активность\n"
        f"5. Дай краткую характеристику деятельности\n\n"
        f"Важно: обращай внимание на региональное представительство и роль в комитете."
    )


async def obzor_zakonodatelstva(ctx: Context) -> str:
    """Обзор законодательства, рассмотренного Советом Федерации.

    Returns:
        Prompt template for legislation overview.
    """
    return (
        "Подготовь обзор законодательства, рассмотренного Советом Федерации.\n\n"
        "Инструкция:\n"
        "1. Получи список законопроектов через poisk_zakonoproektov()\n"
        "2. Проанализируй статус рассмотрения каждого\n"
        "3. Выдели ключевые направления законотворчества\n"
        "4. Отметь одобренные и отклонённые законопроекты\n"
        "5. Оформи как аналитическую справку\n\n"
        "Важно: указывай номера законопроектов и даты рассмотрения."
    )
