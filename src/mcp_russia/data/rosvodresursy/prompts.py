"""Prompts for the Росводресурсы feature."""

from __future__ import annotations

from fastmcp import Context


async def analiz_vodnogo_obekta(context: str, ctx: Context) -> str:
    """Анализ водного объекта.

    Args:
        context: Контекст запроса (например, "анализ реки Волга").

    Returns:
        Prompt template for water body analysis.
    """
    return (
        f"Выполни анализ водного объекта.\n\n"
        f"Контекст: {context}\n\n"
        f"Инструкция:\n"
        f"1. Определи код водного объекта через Государственный водный реестр\n"
        f"2. Получи информацию об объекте через info_vodnogo_obekta()\n"
        f"3. При наличии — получи гидрологические данные\n"
        f"4. Отметь характеристики: длина, площадь бассейна, регион\n"
        f"5. Дай краткую характеристику водного объекта\n\n"
        f"Важно: указывай источник данных — Государственный водный реестр."
    )


async def obzor_vodokhranilishch(ctx: Context) -> str:
    """Обзор состояния крупных водохранилищ РФ.

    Returns:
        Prompt template for reservoir overview.
    """
    return (
        "Подготовь обзор состояния крупных водохранилищ РФ.\n\n"
        "Инструкция:\n"
        "1. Получи список крупных водохранилищ через spisok_vodokhranilishch()\n"
        "2. Для каждого водохранилища получи данные через info_vodokhranilishcha()\n"
        "3. Проанализируй уровень наполнения\n"
        "4. Отметь водохранилища с аномальными показателями\n"
        "5. Оформи как аналитическую справку\n\n"
        "Важно: обращай внимание на признак наполнения (нормальное/низкое/высокое)."
    )
