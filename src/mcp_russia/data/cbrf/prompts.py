"""Промпты модуля ЦБ РФ."""

from __future__ import annotations

from fastmcp import Context


async def analise_valyut(context: str, ctx: Context) -> str:
    """Анализ динамики валютных курсов на основе данных ЦБ РФ.

    Args:
        context: Контекст запроса (например, "анализ рубля к доллару").

    Returns:
        Prompt template for currency analysis.
    """
    return (
        f"Выполни анализ валютных курсов на основе данных ЦБ РФ.\n\n"
        f"Контекст: {context}\n\n"
        f"Инструкция:\n"
        f"1. Получи текущие курсы relevant валют через курсы валют ЦБ РФ\n"
        f"2. Проанализируй динамику изменений\n"
        f"3. Дай краткую характеристику ситуации\n\n"
        f"Важно: данные ЦБ РФ — официальные, но не отражают рыночный курс.\n"
        f"Указывай, что курсы являются официальными и могут отличаться от биржевых."
    )


