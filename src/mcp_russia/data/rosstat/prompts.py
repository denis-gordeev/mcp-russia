"""Промпты модуля Росстата."""

from __future__ import annotations

from fastmcp import Context


async def analiz_regiona(kontekst: str, kontekst_mcp: Context) -> str:
    """Анализ социально-экономического положения региона.

    Аргументы:
        kontekst: Контекст запроса (например, "анализ Москвы").

    Возвращает:
        Шаблон промпта для анализа региона.
    """
    return (
        f"Выполни анализ социально-экономического положения региона.\n\n"
        f"Контекст: {kontekst}\n\n"
        f"Инструкция:\n"
        f"1. Определи код региона через poisk_regiona() или spisok_regionov()\n"
        f"2. Получи данные о населении, ВРП, средней зарплате через informatsiya_o_regionye()\n"
        f"3. Оцени изменение ключевого показателя через dinamika_regiona()\n"
        f"4. Сравни со среднероссийскими показателями через sravnenie_regionov()\n"
        f"5. При необходимости сравни округ через sravnenie_okrugov()\n"
        f"6. Дай краткую характеристику\n\n"
        f"Важно: данные Росстата могут иметь задержку публикации. "
        f"Указывай период данных при цитировании."
    )


