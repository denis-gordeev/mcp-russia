"""Промпты модуля Росстата."""

from __future__ import annotations

from fastmcp import Context


async def analiz_regiona(kontekst: str, kontekst_mcp: Context) -> str:
    """Анализ социально-экономического положения региона.

    Аргументы:
        kontekst: Контекст запроса (например, "анализ Москвы").

    Возвращает:
        Шаблон промпта для анализа региона.
    """
    return (
        f"Выполни анализ социально-экономического положения региона.\n\n"
        f"Контекст: {kontekst}\n\n"
        f"Инструкция:\n"
        f"1. Определи код региона через spisok_regionov()\n"
        f"2. Получи данные о населении, ВРП, средней зарплате\n"
        f"3. Сравни со среднероссийскими показателями\n"
        f"4. Дай краткую характеристику\n\n"
        f"Важно: данные Росстата могут иметь задержку публикации. "
        f"Указывай период данных при цитировании."
    )


async def obzor_inflyacii(kontekst_mcp: Context) -> str:
    """Обзор динамики потребительских цен в России.

    Возвращает:
        Шаблон промпта для обзора инфляции.
    """
    return (
        "Подготовь обзор динамики потребительских цен (инфляции) в России.\n\n"
        "Инструкция:\n"
        "1. Получи данные ИПЦ за последний доступный период\n"
        "2. Отметь месячную и годовую инфляцию\n"
        "3. При наличии данных — сравни с целевым уровнем ЦБ РФ (4%)\n"
        "4. Оформи как краткий аналитический обзор\n\n"
        "Важно: ИПЦ Росстата может отличаться от целевой метрики ЦБ РФ."
    )
