        f"2. Проанализируй распределение по регионам\n"
        f"3. Отметь наиболее криминогенные субъекты\n"
        f"4. Сравни раскрытые и нераскрытые преступления\n"
        f"5. Дай рекомендации по улучшению ситуации\n\n"
