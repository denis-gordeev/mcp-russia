"""Prompts для модуля Anuncios Eleitorais — анализ политической рекламы (legacy).

NOTE: Это слой обратной совместимости (legacy) в рамках mcp-russia.
Данные промпты для анализа бразильской политической рекламы через Meta Ad Library
сохранены для обеспечения обратной совместимости и НЕ являются частью
целевой российской модели данных.

Prompts предоставляют переиспользуемые шаблоны сообщений, направляющие взаимодействие LLM.
"""

from __future__ import annotations


def analise_candidato(nome_candidato: str, pagina_id: str = "") -> str:
    """Анализ рекламной стратегии кандидата или партии через Meta Ad Library (legacy).

    Формирует структурированный анализ затрат, охвата и коммуникационной тактики.

    Args:
        nome_candidato: Имя кандидата или партии для анализа.
        pagina_id: ID страницы Facebook (необязательно, повышает точность).
    """
    instrucoes = (
        f"Подготовь разбор политической рекламы для '{nome_candidato}' "
        "по данным Meta Ad Library.\n\n"
        "Контекст:\n"
        "- В `mcp-russia` это переходный legacy-layer с бразильским покрытием.\n"
        "- Не подавай этот источник как окончательную российскую интеграцию.\n\n"
    )

    if pagina_id:
        instrucoes += (
            f"1. Используй `buscar_anuncios_por_pagina` с ID [{pagina_id}] "
            "для получения объявлений страницы\n"
        )
    else:
        instrucoes += (
            f"1. Используй `buscar_anuncios_eleitorais` с термином '{nome_candidato}' "
            "для поиска релевантных объявлений\n"
        )

    instrucoes += (
        f"2. Используй `analisar_demografia_anuncios` с '{nome_candidato}' для "
        "понимания целевой аудитории\n"
        "3. Сформируй анализ со следующими блоками:\n"
        "   - Количество найденных объявлений\n"
        "   - Общий диапазон расходов\n"
        "   - Наиболее используемые платформы (Facebook, Instagram и т.д.)\n"
        "   - Демографический профиль охваченной аудитории (возраст и пол)\n"
        "   - Штаты с наибольшим охватом\n"
        "   - Основные темы/послания объявлений\n"
        "   - Период наибольшей активности\n"
        "4. Отдельно отметь, что анализ основан на legacy-бразильском покрытии внутри `mcp-russia`"
    )
    return instrucoes


def panorama_eleitoral(estado: str = "", periodo_inicio: str = "", periodo_fim: str = "") -> str:
    """Сводка по политической рекламе в штате или по Бразилии в целом (legacy).

    Даёт обзор активности, крупных рекламодателей и тематических паттернов.

    Args:
        estado: Название штата для фильтрации (напр.: 'Sao Paulo'). Пусто = вся Бразилия.
        periodo_inicio: Дата начала в формате YYYY-mm-dd (необязательно).
        periodo_fim: Дата окончания в формате YYYY-mm-dd (необязательно).
    """
    local = f"в штате {estado}" if estado else "в Бразилии"
    instrucoes = (
        f"Собери обзор политической рекламы {local} по данным Meta Ad Library.\n\n"
        "Контекст:\n"
        "- Используется исторический бразильский dataset Meta Ad Library.\n"
        "- В итоговом тексте явно пометь это как compatibility-layer `mcp-russia`.\n\n"
    )

    if estado:
        instrucoes += f"1. Используй `buscar_anuncios_por_regiao` с регионом ['{estado}'] "
    else:
        instrucoes += "1. Используй `buscar_anuncios_eleitorais` с широкими запросами "

    if periodo_inicio:
        instrucoes += f"с фильтрацией от {periodo_inicio} "
    if periodo_fim:
        instrucoes += f"до {periodo_fim} "

    instrucoes += (
        "для получения выборки объявлений\n"
        "2. Проанализируй результаты и определи:\n"
        "   - Страницы/кандидаты с наибольшим количеством объявлений\n"
        "   - Преобладающие темы и ключевые слова\n"
        "   - Наиболее типичные диапазоны расходов\n"
        "   - Наиболее используемые платформы\n"
        "3. Используй `analisar_demografia_anuncios` для понимания профиля аудитории\n"
        "4. В финале дай executive summary со следующими пунктами:\n"
        "   - Общий обзор активности политической рекламы\n"
        "   - Топ рекламодателей по объёму и расходам\n"
        "   - Основные освещаемые темы\n"
        "   - Наблюдаемые тенденции за период\n"
        "5. Примечание: данные относятся к бразильским выборам"
    )
    return instrucoes


def comparar_candidatos(candidato_a: str, candidato_b: str) -> str:
    """Сравнение рекламных стратегий двух кандидатов или партий (legacy).

    Сопоставляет расходы, охват, аудитории и сообщения.

    Args:
        candidato_a: Имя первого кандидата или партии.
        candidato_b: Имя второго кандидата или партии.
    """
    return (
        f"Сравни политическую рекламу '{candidato_a}' и '{candidato_b}' "
        "по данным Meta Ad Library.\n\n"
        "Контекст:\n"
        "- Используй данные Meta Ad Library как legacy-бразильский слой внутри `mcp-russia`.\n"
        "- Не описывай этот сценарий как готовую российскую интеграцию.\n\n"
        f"1. Используй `buscar_anuncios_eleitorais` с '{candidato_a}' (limit=50)\n"
        f"2. Используй `buscar_anuncios_eleitorais` с '{candidato_b}' (limit=50)\n"
        f"3. Используй `analisar_demografia_anuncios` для '{candidato_a}'\n"
        f"4. Используй `analisar_demografia_anuncios` для '{candidato_b}'\n"
        "5. Сравни и представь:\n"
        "   - Количество объявлений каждого\n"
        "   - Сравнение расходов (диапазоны)\n"
        "   - Различия в целевой аудитории (возраст, пол)\n"
        "   - Различия в региональном распределении\n"
        "   - Предпочтительные платформы каждого\n"
        "   - Различия в темах и тоне сообщений\n"
        "   - У кого предполагаемый охват больше\n"
        "6. Заверши выводом с ключевыми инсайтами и пометкой о переходном статусе источника"
    )
